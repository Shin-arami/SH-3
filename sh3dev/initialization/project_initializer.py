from __future__ import annotations

from pathlib import Path

from sh3dev.initialization.bootstrap import BootstrapGenerator


class ProjectInitializer:
    """Initialize SH-3 project structure."""

    DIRECTORIES = (
        "foundation",
        "infrastructure",
        "runtime",
        "services",
        "kernel",
        "persistence",
        "self_healing",
        "docs/architecture",
        "docs/rfc",
        "docs/release",
        "tests",
        ".github/workflows",
    )

    FILES = (
        "README.md",
        "pyproject.toml",
    )

    def __init__(self) -> None:
        self._bootstrap = BootstrapGenerator()

    def initialize(
        self,
        root: str = "SH-3",
    ) -> dict[str, object]:
        base = Path(root)
        created_directories: list[str] = []
        created_files: list[str] = []

        for directory in self.DIRECTORIES:
            target = base / directory
            target.mkdir(parents=True, exist_ok=True)
            created_directories.append(str(target))

        for file in self.FILES:
            target = base / file
            if not target.exists():
                target.write_text(
                    self._default_content(file),
                    encoding="utf-8",
                )
            created_files.append(str(target))

        bootstrap_files = self._bootstrap.generate(root)

        return {
            "project": base.name,
            "directories": created_directories,
            "files": created_files,
            "bootstrap": bootstrap_files,
            "status": "CREATED",
        }

    def _default_content(self, filename: str) -> str:
        if filename == "README.md":
            return "# SH-3 Project\n\nGenerated by SH-3 DevKit.\n"

        if filename == "pyproject.toml":
            return '[project]\nname = "SH-3"\nversion = "2.1.0"\n'

        return ""
